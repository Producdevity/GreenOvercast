fn glyph(character: u8) Glyph {
    const upper = std.ascii.toUpper(character);
    if (upper >= 'A' and upper <= 'Z') return alphabet[upper - 'A'];
    if (upper >= '0' and upper <= '9') return digits[upper - '0'];
    return switch (upper) {
        ' ' => .{0} ** 7,
        '.' => .{ 0, 0, 0, 0, 0, 0x06, 0x06 },
        ',' => .{ 0, 0, 0, 0, 0x06, 0x04, 0x08 },
        ':' => .{ 0, 0x06, 0x06, 0, 0x06, 0x06, 0 },
        '-' => .{ 0, 0, 0, 0x1f, 0, 0, 0 },
        '/' => .{ 0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10 },
        '+' => .{ 0, 0x04, 0x04, 0x1f, 0x04, 0x04, 0 },
        '\'' => .{ 0x04, 0x04, 0x08, 0, 0, 0, 0 },
        '!' => .{ 0x04, 0x04, 0x04, 0x04, 0x04, 0, 0x04 },
        '&' => .{ 0x0c, 0x12, 0x14, 0x08, 0x15, 0x12, 0x0d },
        '(' => .{ 0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02 },
        ')' => .{ 0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08 },
        else => unknown,
    };
}

pub fn textWidth(text_pointer: [*c]const u8, scale: c_int) c_int {
    if (text_pointer == null) return 0;
    const value = std.mem.span(@as([*:0]const u8, @ptrCast(text_pointer)));
    if (value.len == 0 or scale <= 0) return 0;
    return @as(c_int, @intCast(value.len)) * 6 * scale - scale;
}

pub fn text(
    renderer_pointer: ?*anyopaque,
    initial_x: c_int,
    y: c_int,
    scale: c_int,
    text_pointer: [*c]const u8,
    color: style.Color,
) void {
    const target: *c.SDL_Renderer = @ptrCast(@alignCast(renderer_pointer orelse return));
    if (text_pointer == null) return;
    const value = std.mem.span(@as([*:0]const u8, @ptrCast(text_pointer)));
    if (scale <= 0) return;
    _ = c.SDL_SetRenderDrawColor(target, color.r, color.g, color.b, color.a);
    var x = initial_x;
    for (value) |character| {
        const rows = glyph(character);
        for (rows, 0..) |row_bits, row| {
            for (0..5) |column| {
                const shift: u3 = @intCast(4 - column);
                if (row_bits & (@as(u8, 1) << shift) == 0) continue;
                var pixel = c.SDL_Rect{
                    .x = x + @as(c_int, @intCast(column)) * scale,
                    .y = y + @as(c_int, @intCast(row)) * scale,
                    .w = scale,
                    .h = scale,
                };
                _ = c.SDL_RenderFillRect(target, &pixel);
            }
        }
        x += 6 * scale;
    }
}

pub fn textEllipsized(
    renderer: ?*anyopaque,
    x: c_int,
    y: c_int,
    scale: c_int,
    text_pointer: [*c]const u8,
    max_width: c_int,
    color: style.Color,
) void {
    if (text_pointer == null) return;
    const value = std.mem.span(@as([*:0]const u8, @ptrCast(text_pointer)));
    if (scale <= 0 or max_width <= 0) return;
    const max_characters = @divTrunc(max_width + scale, 6 * scale);
    if (value.len <= @as(usize, @intCast(max_characters))) {
        text(renderer, x, y, scale, text_pointer, color);
        return;
    }
    if (max_characters < 4) return;
    var clipped: [128]u8 = [_]u8{0} ** 128;
    const visible = @min(@as(usize, @intCast(max_characters - 3)), clipped.len - 4);
    @memcpy(clipped[0..visible], value[0..visible]);
    @memcpy(clipped[visible .. visible + 3], "...");
    text(renderer, x, y, scale, @ptrCast(&clipped), color);
}
