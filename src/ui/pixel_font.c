#include "pixel_font.h"

#include <ctype.h>
#include <stdint.h>
#include <string.h>

static void glyph_rows(char character, uint8_t rows[7]) {
    static const uint8_t unknown[7] = {0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04};
    const uint8_t* glyph = unknown;
    static const uint8_t alphabet[][7] = {
        {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E},
        {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E}, {0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E},
        {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F}, {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10},
        {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F}, {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},
        {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E}, {0x07, 0x02, 0x02, 0x02, 0x12, 0x12, 0x0C},
        {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11}, {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F},
        {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11}, {0x11, 0x19, 0x19, 0x15, 0x13, 0x13, 0x11},
        {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10},
        {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D}, {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11},
        {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E}, {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04},
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04},
        {0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A}, {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11},
        {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04}, {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F},
    };
    static const uint8_t digits[][7] = {
        {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}, {0x04, 0x0C, 0x14, 0x04, 0x04, 0x04, 0x1F},
        {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}, {0x1E, 0x01, 0x01, 0x0E, 0x01, 0x01, 0x1E},
        {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}, {0x1F, 0x10, 0x10, 0x1E, 0x01, 0x01, 0x1E},
        {0x0E, 0x10, 0x10, 0x1E, 0x11, 0x11, 0x0E}, {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},
        {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}, {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x01, 0x0E},
    };
    static const uint8_t space[7] = {0};
    static const uint8_t period[7] = {0, 0, 0, 0, 0, 0x06, 0x06};
    static const uint8_t comma[7] = {0, 0, 0, 0, 0x06, 0x04, 0x08};
    static const uint8_t colon[7] = {0, 0x06, 0x06, 0, 0x06, 0x06, 0};
    static const uint8_t dash[7] = {0, 0, 0, 0x1F, 0, 0, 0};
    static const uint8_t slash[7] = {0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10};
    static const uint8_t plus[7] = {0, 0x04, 0x04, 0x1F, 0x04, 0x04, 0};
    static const uint8_t apostrophe[7] = {0x04, 0x04, 0x08, 0, 0, 0, 0};
    static const uint8_t exclamation[7] = {0x04, 0x04, 0x04, 0x04, 0x04, 0, 0x04};
    static const uint8_t ampersand[7] = {0x0C, 0x12, 0x14, 0x08, 0x15, 0x12, 0x0D};
    static const uint8_t left_paren[7] = {0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02};
    static const uint8_t right_paren[7] = {0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08};

    unsigned char upper = (unsigned char)toupper((unsigned char)character);
    if (upper >= 'A' && upper <= 'Z')
        glyph = alphabet[upper - 'A'];
    else if (upper >= '0' && upper <= '9')
        glyph = digits[upper - '0'];
    else {
        switch (upper) {
        case ' ':
            glyph = space;
            break;
        case '.':
            glyph = period;
            break;
        case ',':
            glyph = comma;
            break;
        case ':':
            glyph = colon;
            break;
        case '-':
            glyph = dash;
            break;
        case '/':
            glyph = slash;
            break;
        case '+':
            glyph = plus;
            break;
        case '\'':
            glyph = apostrophe;
            break;
        case '!':
            glyph = exclamation;
            break;
        case '&':
            glyph = ampersand;
            break;
        case '(':
            glyph = left_paren;
            break;
        case ')':
            glyph = right_paren;
            break;
        default:
            break;
        }
    }
    memcpy(rows, glyph, 7);
}

int go_ui_text_width(const char* text, int scale) {
    if (!text || !text[0] || scale <= 0)
        return 0;
    return (int)strlen(text) * 6 * scale - scale;
}

void go_ui_text(SDL_Renderer* renderer, int x, int y, int scale, const char* text,
                SDL_Color color) {
    if (!renderer || !text || scale <= 0)
        return;
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    for (const char* cursor = text; *cursor; cursor++, x += 6 * scale) {
        uint8_t rows[7];
        glyph_rows(*cursor, rows);
        for (int row = 0; row < 7; row++) {
            for (int column = 0; column < 5; column++) {
                if (!(rows[row] & (1U << (4 - column))))
                    continue;
                SDL_Rect pixel = {x + column * scale, y + row * scale, scale, scale};
                SDL_RenderFillRect(renderer, &pixel);
            }
        }
    }
}

void go_ui_text_ellipsized(SDL_Renderer* renderer, int x, int y, int scale, const char* text,
                           int max_width, SDL_Color color) {
    if (!text || max_width <= 0)
        return;
    int max_characters = (max_width + scale) / (6 * scale);
    size_t length = strlen(text);
    if ((int)length <= max_characters) {
        go_ui_text(renderer, x, y, scale, text, color);
        return;
    }
    if (max_characters < 4)
        return;
    char clipped[128];
    size_t visible = (size_t)(max_characters - 3);
    if (visible > sizeof(clipped) - 4)
        visible = sizeof(clipped) - 4;
    memcpy(clipped, text, visible);
    memcpy(clipped + visible, "...", 4);
    go_ui_text(renderer, x, y, scale, clipped, color);
}
